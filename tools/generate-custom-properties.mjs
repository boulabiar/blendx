import { mkdir, readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const sourcePath = `${root}schema/custom-properties.txt`
const tsPath = `${root}src/generated/custom-properties.ts`
const headerPath = `${root}native/generated_custom_properties.h`

const source = await readFile(sourcePath, "utf8")
const definitions = source.split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("#"))
  .map((line, index) => {
    const [name, invalidation, extra] = line.split(/\s+/)
    if (!name || !invalidation || extra || !["paint", "measure", "special"].includes(invalidation)) {
      throw new Error(`invalid custom property at line ${index + 1}: ${line}`)
    }
    return { name, invalidation }
  })

const enumName = (name) => name[0].toUpperCase() + name.slice(1)
const ts = `// Generated by tools/generate-custom-properties.mjs; do not edit.\n` +
  `export const customProperties = ${JSON.stringify(definitions.map(({ name }) => name), null, 2)} as const\n` +
  `export const customPropertyIds = Object.fromEntries(customProperties.map((name, id) => [name, id])) as Record<(typeof customProperties)[number], number>\n`
const header = `// Generated by tools/generate-custom-properties.mjs; do not edit.\n#pragma once\n\n#include <array>\n#include <cstdint>\n#include <string_view>\n\nnamespace blendx {\n\nenum class CustomPropertyInvalidation : uint8_t { kPaint, kMeasure, kSpecial };\nenum class CustomPropertyId : uint16_t {\n${definitions.map(({ name }) => `  k${enumName(name)},`).join("\n")}\n};\nstruct CustomPropertyDefinition {\n  CustomPropertyId id;\n  std::string_view name;\n  CustomPropertyInvalidation invalidation;\n};\ninline constexpr std::array<CustomPropertyDefinition, ${definitions.length}> kCustomProperties = {{\n${definitions.map(({ name, invalidation }) => `  {CustomPropertyId::k${enumName(name)}, "${name}", CustomPropertyInvalidation::k${enumName(invalidation)}},`).join("\n")}\n}};\ninline constexpr const CustomPropertyDefinition* find_custom_property(std::string_view name) {\n  for (const auto& property : kCustomProperties) if (property.name == name) return &property;\n  return nullptr;\n}\n\n}  // namespace blendx\n`

const generated = [[tsPath, ts], [headerPath, header]]
if (process.argv.includes("--check")) {
  for (const [path, expected] of generated) {
    const actual = await readFile(path, "utf8").catch(() => "")
    if (actual !== expected) throw new Error(`${path} is stale; run npm run generate:properties`)
  }
} else {
  await mkdir(`${root}src/generated`, { recursive: true })
  for (const [path, contents] of generated) await writeFile(path, contents)
}
